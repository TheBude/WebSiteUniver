export function getSamduPageContent(slugOrLabel, language = 'uz') {
  if (!slugOrLabel) return null;

  const cleanQuery = decodeURIComponent(slugOrLabel).replace(/^#/, '').trim();

  for (const [key, page] of Object.entries(samduMajorPages)) {
    if (key.toLowerCase() === cleanQuery.toLowerCase() || page.id === cleanQuery.toLowerCase()) {
      return formatPage(page, language, key);
    }
  }

  return generateContextualPage(cleanQuery, language);
}

function formatPage(page, lang, rawKey) {
  return {
    id: page.id,
    title: page.title[lang] || page.title.uz,
    category: page.category[lang] || page.category.uz,
    lead: page.lead[lang] || page.lead.uz,
    paragraphs: page.paragraphs[lang] || page.paragraphs.uz || [],
    image: page.image,
    facts: (page.facts || []).map((f) => ({
      label: f.label[lang] || f.label.uz,
      value: f.value[lang] || f.value.uz,
    })),
    contact: page.contact,
    rawKey,
  };
}

